def prompts(ir):
    c = {x['id']:x for x in ir['claims']}
    keys = ['scenario.residential_gross_sf','scenario.residential_net_sf','scenario.home_equivalents']
    bound = [k for k in keys if k in c]
    values = '; '.join(c[k]['label']+': '+str(c[k]['value'])+' '+c[k]['unit'] for k in bound)
    prompt = ('Create a clear labeled area-budget diagram on a plain background. '+values+'. ' if bound else 'Create a text-led evidence card for this parcel investigation. ')
    prompt += 'Include the label: Illustrative investigation, not an approved or physically validated building. Do not depict building geometry, height, footprints, streetscape, existing occupants, legal capacity, affordability, or financial feasibility as established.'
    return {'version':'0.2.0','resolved_bbl':ir['resolved_bbl'],'mode':'diagram_only','purpose':'Downstream visual raw material; no image is generated by this workflow.','prompt':prompt,'bindings':[{'claim_id':k,'value':c[k]['value'],'unit':c[k]['unit']} for k in bound],'required_labels':['Illustrative investigation','Area budget does not establish building fit'],'unresolved_constraints':[x['id'] for x in ir['claims'] if x['kind']=='unknown'],'geometry_status':'unverified','model_sha256':None}

def opening(ir, receipts, execution):
    """Short deterministic view: every analytical assertion links to a typed claim."""
    c = {x['id']: x for x in ir['claims']}
    def link(cid, label=None):
        return '['+(label or c[cid]['label'])+'](#'+cid.replace('.', '-')+')'
    labels = {
        EvidenceMode.LIVE: 'Live collection was invoked for this run; inspect each source status below.',
        EvidenceMode.REPLAY: 'Cached replay. This step reused retained source responses; it did not query the APIs.',
        EvidenceMode.ANALYSIS: 'Analysis of retained source snapshots. This modeling step did not query the APIs.',
        EvidenceMode.UNKNOWN: 'Collection mode was not recorded. Do not describe this packet as a live collection.',
    }
    rows = ['## Read this first', '', '**Evidence origin:** '+labels[execution.mode], '',
            'Execution metadata: [execution.json](execution.json). Raw-source retrieval dates: [receipts.json](receipts.json). Retrieval is not a field-observation date or a guarantee of current conditions.', '']
    dates = sorted({r['retrieved_at'] for r in receipts if r.get('retrieved_at')})
    if dates:rows += ['**Source retrieval range (UTC):** '+dates[0]+' through '+dates[-1]+'.', '']
    if 'pluto.0.version' in c:
        rows += ['**PLUTO row vintage:** '+str(c['pluto.0.version']['value'])+' — '+link('pluto.0.version')+'.', '']
    failed = [r['id'] for r in receipts if r['status'] != 'ok']
    truncated = [r['id'] for r in receipts if r.get('truncated')]
    rows += ['**Coverage flags:** '+('failed: '+', '.join(failed) if failed else 'no adapter failures recorded')+'; '+('truncated: '+', '.join(truncated) if truncated else 'no row-cap truncation recorded')+'. Successful bounded queries are not proof of complete history.', '',
             '### What these records support', '']
    selected = [('address','Recorded address'),('lotarea','Recorded lot area'),('unitsres','Recorded residential units'),('zonedist1','Recorded primary zoning')]
    for field, label in selected:
        cid='pluto.0.'+field
        if cid in c:rows.append('- '+label+': '+str(c[cid]['value'])+' — '+link(cid)+'.')
    if not any('pluto.0.'+f in c for f,_ in selected):rows.append('- No selected PLUTO parcel facts are available; review failed sources and retained receipts.')
    if ir['housing_signal_claims']:
        rows += ['- Historical positive dwelling-unit signals need reconciliation: '+', '.join(link(cid,str(c[cid]['value'])+' units as recorded') for cid in ir['housing_signal_claims'][:3])+'. This is not a present occupancy count; see the full signal section.']
    rows += ['', '### Supplied assumptions and conditional result', '']
    assumptions=[x for x in ir['claims'] if x['kind']=='assumption']
    if assumptions:
        rows += ['- '+str(x['value'])+' '+x['unit']+' — '+link(x['id'])+'.' for x in assumptions]
    else:rows += ['- No area assumptions were supplied. Evidence-only output does not invent a development program.']
    cid='scenario.home_equivalents'
    if cid in c:rows += ['- Conditional area-budget result: '+str(c[cid]['value'])+' home-equivalents — '+link(cid)+'. This does not establish feasible homes, zoning capacity or an affordable program.']
    rows += ['', '### What remains unresolved / inputs to continue', '']
    prompts = [('current_use','Current-use, lease and lawful-occupancy evidence'),('title','Title, site control and owner intent'),('entitlement','Applicable zoning and approvals'),('physical_fit','Survey, envelope and layout evidence'),('environment','Environmental requirements and studies'),('finance','Program rules, costs and financing'),('transit','Walked access, service and job-access evidence')]
    for key, label in prompts:
        cid='unknown.'+key
        if cid in c:rows.append('- '+label+' — '+link(cid)+'.')
    if 'review.next_diligence' in c:
        rows += ['', 'These are unresolved input categories, not a ranked action plan. '+link('review.next_diligence','The discussion checklist')+' is an unreviewed author judgment.']
    rows += ['', 'Detailed source coverage, calculations and the complete claim register follow. This summary is an extract of the same claims; it adds no professional clearance.', '']
    return rows


def projections(ir, receipts, execution=None):
    claims = ir['claims']; by_id = {x['id']:x for x in claims}; sources = {x['id']:x for x in receipts}
    pluto_labels = {'address':'Recorded address','bbl':'Tax-lot BBL','bldgarea':'Recorded building area (sf)','bldgclass':'Recorded building class','lotarea':'Recorded lot area (sf)','unitsres':'Recorded residential units','unitstotal':'Recorded total units','residfar':'Recorded residential FAR (legal applicability unreviewed)','builtfar':'Recorded built FAR','numfloors':'Recorded floor count','zonedist1':'Recorded primary zoning district','zonedist2':'Recorded second zoning district','overlay1':'Recorded overlay','spdist1':'Recorded special district','spdist2':'Recorded second special district','irrlotcode':'Recorded irregular-lot flag','edesignum':'Recorded environmental designation','version':'Dataset row version'}
    rows = ['# Parcel investigation '+ir['resolved_bbl'], '', ir['question'], '',
            '**Partial playbook under development.** This packet preserves evidence and conditional arithmetic; it does not establish site availability, a lawful use, legal capacity, building fit or funded feasibility.', '',
            *opening(ir,receipts,execution or ExecutionContext(EvidenceMode.UNKNOWN)),
            '## Source coverage', '', '| Source | Status | Returned rows | Truncated | Retrieved UTC |', '| --- | --- | --- | --- | --- |']
    for r in receipts:
        rows.append('| '+r['id']+' | '+r['status']+' | '+str(r['returned_rows'])+' | '+str(r['truncated'])+' | '+r['retrieved_at']+' |')
    rows += ['', 'A failed request is missing evidence, not zero records. Counts describe returned rows, not unique projects. Empty exact-BBL results do not establish no housing, no violations or no activity.', '', '## Recorded parcel facts', '']
    for x in claims:
        if x['id'].startswith('pluto.0.'):
            key=x['id'].rsplit('.',1)[-1]
            rows.append('- '+pluto_labels.get(key,key)+': '+str(x['value'])+' — [source](#'+x['id'].replace('.','-')+')')
    rows += ['', '## Historical housing signals requiring reconciliation', '']
    if ir['housing_signal_claims']:
        for key in ir['housing_signal_claims']:
            x=by_id[key]; prefix=key.rsplit('.',1)[0]
            desc=by_id.get(prefix+'.job_description',{}).get('value','Description not returned')
            date=by_id.get(prefix+'.pre__filing_date',by_id.get(prefix+'.filing_date',{})).get('value','Date not returned')
            rows.append('- Historical '+key.rsplit('.',1)[-1].replace('_',' ')+': '+str(x['value'])+'; filing date '+str(date)+'; '+str(desc)+' — [source](#'+key.replace('.','-')+')')
        rows += ['', 'These fields describe historical existing/proposed units. They are not a current occupancy count and are not summed across documents or jobs. Their relationship to PLUTO and lawful/current use needs review.']
    else:rows += ['No positive dwelling-unit signal was extracted from the returned DOB rows. This does not establish absence of housing; review collection status, truncation and missing history.']
    rows += ['', '## Scenario and calculation steps', '']
    if ir['scenario_name']:
        rows += [ir['scenario_name'], '', '| Claim | Value | Unit | Basis |', '| --- | --- | --- | --- |']
        for x in claims:
            if x['id'].startswith('scenario.'):
                basis=x['rationale'] if x['kind']=='assumption' else (' '+{'subtract':'−','multiply':'×','divide':'÷'}[x['formula']]+' ').join(str(by_id[k]['value']) for k in x['inputs'])
                rows.append('| ['+x['label']+'](#'+x['id'].replace('.','-')+') | '+str(x['value'])+' | '+x['unit']+' | '+basis.replace('|','/')+' |')
        rows += ['', 'Home-equivalents are an area quotient, not a verified count of homes. The gross-to-lot ratio is not zoning FAR. No rents, affordability eligibility, costs or financing commitments are inferred.']
    else:rows += ['No scenario supplied; the workflow produced evidence without inventing assumptions or a home count.']
    rows += ['', '## Unknowns and next questions', '']
    for x in claims:
        if x['kind']=='unknown': rows.append('- **'+x['label']+'**: '+x['rationale'])
        elif x['kind']=='judgment': rows.append('- **'+x['label']+' — unreviewed judgment**: '+x['rationale'])
    rows += ['', '## Provenance register', '', 'Raw responses, retrieval receipts, request inputs, calculation steps and machine-readable claims are included alongside this packet. Retrieval dates are not field observation dates. Citations establish the selected value, not interpretation or complete coverage.', '']
    for x in claims:
        rows += ['<a id="'+x['id'].replace('.','-')+'"></a>', '', '**'+x['id']+'** ['+x['kind']+'] '+x['label']+': '+str(x['value'])+' ('+x['unit']+')', '']
        for ref in x['references']:
            r=sources[ref['source_id']]
            rows += ['Source: ['+ref['source_id']+' raw response]('+r['body_path']+'), JSON pointer `'+(ref['pointer'] or '/')+'`; SHA256 `'+ref['sha256']+'`. [Exact request]('+r['url']+').', '']
        if x['inputs']:rows += ['Depends on: '+', '.join('['+k+'](#'+k.replace('.','-')+')' for k in x['inputs'])+'.', '']
        if x['rationale']:rows += [x['rationale'], '']
    rows += ['## Source limits and terms', '']
    for r in receipts:
        rows += ['- **'+r['id']+'** — '+r['limits']+' [Publisher dataset]('+r['catalog_url']+'). [Terms]('+r['terms_url']+').']
    md='\n'.join(rows)+'\n'
    # Deliberately small Markdown subset; escape API/user text before adding links.
    def inline(s):
        s=html.escape(s)
        s=re.sub(r'\[([^\]]+)\]\(([^\s)]+)\)',lambda m: '<a href="'+m[2]+'">'+m[1]+'</a>' if m[2].startswith(('https://','sources/','#')) or m[2] in {'execution.json','receipts.json','ir.json','request.json'} else m[1],s)
        s=re.sub(r'\*\*([^*]+)\*\*',r'<strong>\1</strong>',s)
        s=re.sub(r'`([^`]+)`',r'<code>\1</code>',s)
        return s
    parts=[]; table=False
    for line in rows:
        if line.startswith('|'):
            if not table:parts.append('<table>');table=True
            if set(line.replace('|','').replace(' ','').replace(':','')) == {'-'}:continue
            parts.append('<tr>'+''.join('<td>'+inline(s.strip())+'</td>' for s in line.strip('|').split('|'))+'</tr>');continue
        if table:parts.append('</table>');table=False
        anchor=re.fullmatch(r'<a id="([a-zA-Z0-9_-]+)"></a>',line)
        if anchor:parts.append('<a id="'+anchor[1]+'"></a>')
        elif line.startswith('### '):parts.append('<h3>'+inline(line[4:])+'</h3>')
        elif line.startswith('## '):parts.append('<h2>'+inline(line[3:])+'</h2>')
        elif line.startswith('# '):parts.append('<h1>'+inline(line[2:])+'</h1>')
        elif line:parts.append('<p>'+inline(line)+'</p>')
    if table:parts.append('</table>')
    page='<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Parcel investigation '+ir['resolved_bbl']+'</title><style>body{font:17px/1.55 system-ui,sans-serif;max-width:980px;margin:40px auto;padding:0 22px;color:#182a34}h1,h2{line-height:1.2}h2{margin-top:2em}a{color:#065e91;overflow-wrap:anywhere}table{border-collapse:collapse;display:block;overflow:auto;font-size:14px}td{padding:9px;border:1px solid #c8d3da;vertical-align:top}tr:first-child{background:#eef3f5}code{overflow-wrap:anywhere}p{overflow-wrap:anywhere}</style><main>'+''.join(parts)+'</main></html>\n'
    output=io.StringIO();writer=csv.writer(output,lineterminator="\n");writer.writerow(['claim_id','kind','value','unit','formula','inputs','rationale'])
    for x in claims:
        if x['kind'] in {'assumption','calculation'}:writer.writerow([x['id'],x['kind'],x['value'],x['unit'],x['formula'] or '',','.join(x['inputs']),x['rationale'] or ''])
    return md,page,output.getvalue()
